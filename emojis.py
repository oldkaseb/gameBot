def render_emojis(text: str) -> str:
    if not text or "[" not in text:
        return text
    if "<tg-emoji" in text:
        return text

    if not PREMIUM_EMOJIS_ENABLED:
        def repl(m):
            return BASE_MAP.get(m.group(1), "⭐")
        return EMOJI_ID_RE.sub(repl, text)

    def repl(m):
        eid = m.group(1)
        base = BASE_MAP.get(eid, "⭐")
        return f'<tg-emoji emoji-id="{eid}">{base}</tg-emoji>'

    return EMOJI_ID_RE.sub(repl, text)


def strip_custom_emoji_tags(text: str, keep_unicode: bool = True) -> str:
    """حذف تگ‌های tg-emoji. اگر keep_unicode=False، حتی fallback یونیکد هم حذف می‌شود"""
    if not text or "<tg-emoji" not in text:
        return text
    if keep_unicode:
        return TG_EMOJI_TAG_RE.sub(lambda m: m.group(2) or "", text)
    return TG_EMOJI_TAG_RE.sub("", text)


def extract_emoji_ids(text: str) -> list[str]:
    if not text or "<tg-emoji" not in text:
        return []
    return TG_EMOJI_TAG_RE.findall(text)


def strip_emoji_id(text: str):
    if not text:
        return text or "·", None
    m = EMOJI_ID_RE.search(text)
    if not m:
        return text, None
    cleaned = (text[:m.start()] + text[m.end():]).strip() or "·"
    return cleaned, m.group(1)
